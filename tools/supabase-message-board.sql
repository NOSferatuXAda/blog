-- Message board schema for Supabase
-- Paste this whole file into Supabase Dashboard -> SQL Editor -> Run.

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  name text,
  content text not null check (char_length(content) between 1 and 500),
  anonymous boolean not null default true,
  is_visible boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.messages enable row level security;

create policy "public can read visible messages"
  on public.messages for select
  using (is_visible = true);

create policy "visitors can insert messages"
  on public.messages for insert
  to anon
  with check (
    char_length(content) between 1 and 500
    and (
      (anonymous = true and name is null)
      or (anonymous = false and name is not null and char_length(name) between 1 and 20)
    )
  );

-- Column-level insert privileges:
-- anon may only write name / content / anonymous.
-- It cannot forge id, created_at or is_visible.
revoke insert, update, delete on public.messages from anon;
grant select on public.messages to anon;
grant insert (name, content, anonymous) on public.messages to anon;
grant usage, select on sequence public.messages_id_seq to anon;
